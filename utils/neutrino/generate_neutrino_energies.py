#!/usr/bin/env python3
"""Generate GridFire's table of average neutrino energies for REACLIB weak reactions from MESA's rate data.

REACLIB weak rates carry no neutrino information, so GridFire looks up the average energy carried away by the
neutrino per reaction. The values come from MESA ($MESA_DIR/data/rates_data):

  * reactions.list   - pp, pep, hep, 7Be, 8B (Bahcall, Phys. Rev. C 65, 025801, 2002)
  * weak_info.list   - single parent -> daughter decays and captures (13N and 15O from Bahcall 2002, 17F from Bahcall
                       1997; most heavier entries evaluated from weaklib at logT = 7.5, logRho = 4, Ye = 0.5, eta = 0)

    generate_neutrino_energies.py > src/lib/reaction/weak/neutrino_energies_data.inc
"""
import os
import re
import sys
from pathlib import Path


def fortran_float(text):
    return float(text.strip().lower().replace("d", "e"))


def main():
    mesa_dir = os.environ.get("MESA_DIR")
    if not mesa_dir:
        sys.exit("set MESA_DIR")
    rates_data = Path(mesa_dir) / "data" / "rates_data"
    version = (Path(mesa_dir) / "data" / "version_number").read_text().strip()

    # Multi-particle weak reactions from reactions.list (fixed format: name in 1-36, Qneu in columns 128-143)
    special = {}
    for line in (rates_data / "reactions.list").read_text().splitlines():
        if line.startswith("!") or not line.strip():
            continue
        name = line.split()[0]
        qneu = line[127:143].strip()
        if name in ("r_h1_h1_wk_h2", "r_h1_h1_ec_h2", "r_h1_he3_wk_he4", "r_b8_wk_he4_he4") and qneu:
            special[name] = fortran_float(qneu)

    # Parent -> daughter decays and captures from weak_info.list
    decays = []
    for line in (rates_data / "weak_info.list").read_text().splitlines():
        parts = line.split()
        if len(parts) >= 4 and not line.lstrip().startswith("!") and parts[0] != "from":
            decays.append((parts[0], parts[1], fortran_float(parts[3])))

    # Keys: participants as MESA iso names. pp and pep share species, so the lepton disambiguates them.
    special_keys = {
        "r_h1_h1_wk_h2": ("h1 h1", "h2", "e+"),
        "r_h1_h1_ec_h2": ("h1 h1", "h2", "e-"),
        "r_h1_he3_wk_he4": ("h1 he3", "he4", "e+"),
        "r_b8_wk_he4_he4": ("b8", "he4 he4", "e+"),
    }
    print(f"// Generated by utils/neutrino/generate_neutrino_energies.py from MESA {version} data/rates_data. Do not edit.")
    print("// {reactants (sorted MESA iso names), products (sorted), lepton (\"e+\", \"e-\", or \"\" for any), <E_nu> [MeV]}")
    for name, (reactants, products, lepton) in special_keys.items():
        print(f'{{"{reactants}", "{products}", "{lepton}", {special[name]!r}}}, // {name} (Bahcall 2002)')
    for parent, daughter, qneu in decays:
        print(f'{{"{parent}", "{daughter}", "", {qneu!r}}},')


if __name__ == "__main__":
    main()
